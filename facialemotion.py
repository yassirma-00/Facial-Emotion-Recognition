def getData(filename):
    Y = []
    X = []
    with open(filename, 'r') as f:
        next(f)  # sauter la première ligne d'en-tête
        for line in f:
            row = line.strip().split(',')
            label = int(row[0])
            pixels = np.array([int(p) for p in row[1].split()], dtype=np.float32)
            X.append(pixels)
            Y.append(label)

    X = np.array(X) / 255.0  # Normaliser entre 0 et 1
    Y = np.array(Y)
    return X, Y

